const fs = require('fs');
const path = require('path');

/**
 * Generate a hook catalog table from config/hooks.php
 * Output: Markdown table for pasting into developer/plugins/hooks.mdx
 *
 * Usage: node scripts/generate-hook-catalog.js [path/to/hooks.php]
 */

const HOOKS_FILE = process.argv[2] || 'config/hooks.php';

function extractHooks(content) {
  const hooks = [];
  const hookRegex = /\$eventManager->(addAction|applyFilter)\(\s*['"]([\w.]+)['"]\s*(?:,\s*\[([\w\s,']+)\])?/g;
  let match;

  while ((match = hookRegex.exec(content)) !== null) {
    hooks.push({
      type: match[1] === 'addAction' ? 'Action' : 'Filter',
      name: match[2],
      args: match[3] ? match[3].split(',').map(s => s.trim().replace(/'/g, '')) : []
    });
  }

  return hooks;
}

function categorizeHooks(hooks) {
  const categories = {
    'Payment': [],
    'Gateway': [],
    'Checkout': [],
    'System': [],
    'Admin': [],
    'Plugin': [],
    'Other': []
  };

  for (const hook of hooks) {
    const name = hook.name.toLowerCase();
    if (name.includes('payment.')) {
      categories['Payment'].push(hook);
    } else if (name.includes('gateway.')) {
      categories['Gateway'].push(hook);
    } else if (name.includes('checkout.')) {
      categories['Checkout'].push(hook);
    } else if (name.includes('system.') || name.includes('kernel.') || name.includes('middleware')) {
      categories['System'].push(hook);
    } else if (name.includes('admin.')) {
      categories['Admin'].push(hook);
    } else if (name.includes('plugin.')) {
      categories['Plugin'].push(hook);
    } else {
      categories['Other'].push(hook);
    }
  }

  return categories;
}

function generateMarkdown(categorizedHooks) {
  let output = '<!-- Auto-generated by scripts/generate-hook-catalog.js -->\n';
  output += '<!-- Do not edit manually — regenerate from config/hooks.php -->\n\n';

  for (const [category, hooks] of Object.entries(categorizedHooks)) {
    if (hooks.length === 0) continue;

    output += `### ${category} Hooks\n\n`;
    output += '| Hook Name | Type | Accepted Args |\n';
    output += '|-----------|------|---------------|\n';

    for (const hook of hooks) {
      output += '| `' + hook.name + '` | ' + hook.type + ' | ' + (hook.args.length > 0 ? hook.args.join(', ') : '—') + ' |\n';
    }

    output += '\n';
  }

  return output;
}

// Main
try {
  const hooksPath = path.resolve(process.cwd(), HOOKS_FILE);
  if (!fs.existsSync(hooksPath)) {
    console.error(`Hooks file not found: ${hooksPath}`);
    console.error('Usage: node scripts/generate-hook-catalog.js [path/to/hooks.php]');
    process.exit(1);
  }

  const content = fs.readFileSync(hooksPath, 'utf-8');
  const hooks = extractHooks(content);
  const categorized = categorizeHooks(hooks);
  const markdown = generateMarkdown(categorized);

  console.log(markdown);
  console.error(`\nExtracted ${hooks.length} hooks from ${HOOKS_FILE}`);
} catch (err) {
  console.error('Error:', err.message);
  process.exit(1);
}
